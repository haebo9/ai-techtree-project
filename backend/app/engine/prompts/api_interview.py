PROMPT_VARIANTS = {
    "short": SHORT_MODE_PROMPT,
    "long": LONG_MODE_PROMPT,
}


def normalize_interview_mode(mode: str | None) -> str:
    normalized = (mode or "long").strip().lower()
    return "short" if normalized == "short" else "long"


def build_realtime_interviewer_prompt(*, interview_mode: str | None, **kwargs: str) -> str:
    mode = normalize_interview_mode(interview_mode)
    return COMMON_INTERVIEWER_PROMPT.format(
        mode_prompt=PROMPT_VARIANTS[mode],
        **kwargs,
    )


# Backward-compatible default for older LangGraph code paths.
INTERVIEWER_SYSTEM_PROMPT = COMMON_INTERVIEWER_PROMPT.replace("{mode_prompt}", LONG_MODE_PROMPT)
